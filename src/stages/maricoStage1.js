// マリコ「パズル×アクション」ステージ1のレイアウト定義。stage1.js
// （主人公用）と同じ座標系・床/障害物/ゴールの表現に加え、スイッチと
// ブロックによるパズル要素を持つ。
//
// レイアウト（x座標の区画、worldHeight=540、床上面はy=480付近）:
//   0-300     床1（スタート。スイッチAを設置。ここは連続した床なので
//             スタート直後に触れられる）
//   300-500   穴1（スイッチAをONにすると橋1が出現して渡れる）
//   500-800   床2（壁ゾーンの手前。スイッチBを設置）
//   800-1000  壁ゾーン（スイッチBがOFFの間、壁ブロックが通行を塞ぐ。
//             スイッチBをONにすると壁が消えて通過できる）
//   1000-1300 床3（穴2の手前）
//   1300-1500 穴2（スイッチAで出した橋2で渡る。橋1と同じスイッチAが
//             同時に制御する＝1スイッチが複数ブロックを一括操作する例。
//             スタート直後にONにしたスイッチAをそのまま維持していれば
//             ここも渡れる）
//   1500-1900 床4（ゴール手前、障害物1個）
//   1900-2100 ゴール
//
// 解法: 床1でスイッチAをON（橋1・橋2が同時に出現）→橋1で穴1を渡る→
// 床2でスイッチBをON（壁が消える）→壁ゾーンを通過→床3→橋2で穴2を
// 渡る→床4→ゴール。スイッチはトグル式だが、この構成では一度ONにした
// ら最後までONのままで解ける（誤って再度触れてOFFに戻すと詰むため、
// スイッチの位置はどちらも「通過する床の中心」に置き、素通りできる
// よう配置している）。
